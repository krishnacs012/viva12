def choose_from_list(
    prompt,
    options
):

    print(prompt)

    for i, option in enumerate(
        options,
        1
    ):

        print(
            f"  {i}. {option}"
        )

    while True:

        choice = input(
            f"Choose 1-{len(options)}: "
        ).strip()

        if (
            choice.isdigit()
            and
            1 <= int(choice) <= len(options)
        ):

            return options[
                int(choice) - 1
            ]

        print(
            "Invalid choice, try again."
        )


