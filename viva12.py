def main():

    print("=" * 30)

    print(
        "   AI VIVA GENERATOR (MCQ)"
    )

    print("=" * 30)


    topic = choose_from_list(
        "\nSelect a topic:",
        TOPICS
    )


    level = choose_from_list(
        "\nSelect starting difficulty:",
        LEVELS
    )


    while True:

        n = input(
            "\nHow many questions? "
        ).strip()

        if (
            n.isdigit()
            and int(n) > 0
        ):

            num_questions = int(n)

            break

        print(
            "Please enter a positive number."
        )


    llm = get_llm()


    session = VivaSession(
        llm,
        topic,
        level,
        num_questions
    )


    session.run()



main()
