# ==========================================
# 5. VIVA SESSION
# ==========================================

class VivaSession:

    def __init__(
        self,
        llm,
        topic,
        start_level,
        num_questions
    ):

        self.llm = llm
        self.topic = topic

        self.difficulty = LEVEL_TO_NUM[start_level]

        self.num_questions = num_questions

        self.question_chain = (
            question_prompt
            | llm.with_structured_output(VivaQuestionSet)
        )

        self.rec_chain = None

        self.questions = []

        self.asked_questions = []

        self.results = []


    # ======================================
    # GENERATE QUESTION BANK ONCE
    # ======================================

    def generate_question_bank(self):

        print("\nGenerating viva questions...")

        question_set = self.question_chain.invoke({
            "topic": self.topic
        })

        self.questions = question_set.questions

        print(
            f"✓ {len(self.questions)} questions generated."
        )


    # ======================================
    # SELECT QUESTION LOCALLY
    # ======================================

    def next_question(self):

        # Find questions matching current difficulty

        available = [
            q for q in self.questions
            if q.difficulty == self.difficulty
            and q.question not in self.asked_questions
        ]

        # If no question at current difficulty,
        # use any unused question

        if not available:

            available = [
                q for q in self.questions
                if q.question not in self.asked_questions
            ]

        # Safety check

        if not available:

            return None

        q = available[0]

        self.asked_questions.append(
            q.question
        )

        return q


    # ======================================
    # ADAPT DIFFICULTY LOCALLY
    # ======================================

    def adjust_difficulty(self, correct):

        if correct:

            self.difficulty = min(
                3,
                self.difficulty + 1
            )

        else:

            self.difficulty = max(
                1,
                self.difficulty - 1
            )


    # ======================================
    # RECORD RESULT
    # ======================================

    def record(
        self,
        question,
        concept,
        correct
    ):

        self.results.append({

            "question": question,

            "concept": concept,

            "correct": correct

        })


    # ======================================
    # GET USER ANSWER
    # ======================================

    def ask_for_choice(self):

        while True:

            raw = input(
                "Your answer (A/B/C/D): "
            ).strip().upper()

            # Accept A/B/C/D

            if raw in OPTION_LETTERS:

                return OPTION_LETTERS.index(raw)

            # Also accept 1/2/3/4

            if raw in ["1", "2", "3", "4"]:

                return int(raw) - 1

            print(
                "Please enter A, B, C, D "
                "or 1, 2, 3, 4."
            )


    # ======================================
    # RUN VIVA
    # ======================================

    def run(self):

        print(
            f"\nStarting viva on '{self.topic}' "
            f"(starting level: "
            f"{NUM_TO_LEVEL[self.difficulty]})\n"
        )

        # ONE GEMINI CALL

        self.generate_question_bank()

        # Ask questions locally

        for i in range(
            1,
            self.num_questions + 1
        ):

            q = self.next_question()

            if q is None:

                print(
                    "\nNo more questions available."
                )

                break

            print(
                f"\nQ{i}. "
                f"[{NUM_TO_LEVEL[q.difficulty]}] "
                f"{q.question}"
            )

            for letter, option in zip(
                OPTION_LETTERS,
                q.options
            ):

                print(
                    f"   {letter}. {option}"
                )

            chosen_index = self.ask_for_choice()

            correct = (
                chosen_index ==
                q.correct_index
            )

            if correct:

                print("\n✅ Correct!")

            else:

                correct_letter = (
                    OPTION_LETTERS[
                        q.correct_index
                    ]
                )

                print(
                    f"\n❌ Incorrect."
                )

                print(
                    f"Correct answer: "
                    f"{correct_letter}. "
                    f"{q.options[q.correct_index]}"
                )

            print(
                f"Explanation: "
                f"{q.explanation}"
            )

            self.record(
                q.question,
                q.concept,
                correct
            )

            self.adjust_difficulty(
                correct
            )

            if correct:

                print(
                    "Next question will be harder."
                )

            else:

                print(
                    "Next question will be easier."
                )

        self.print_report()


    # ======================================
    # FINAL REPORT
    # ======================================

    def print_report(self):

        total = len(self.results)

        correct_count = sum(
            1
            for r in self.results
            if r["correct"]
        )

        pct = (
            round(
                100 *
                correct_count /
                total
            )
            if total
            else 0
        )

        strong_concepts = sorted({
            r["concept"]
            for r in self.results
            if r["correct"]
        })

        weak_concepts = sorted({
            r["concept"]
            for r in self.results
            if not r["correct"]
        })


        print("\n")
        print("━" * 30)

        print(
            "       VIVA REPORT"
        )

        print("━" * 30)

        print(
            f"Topic: {self.topic}\n"
        )

        print(
            f"Questions:  {total}"
        )

        print(
            f"Correct:    {correct_count}"
        )

        print(
            f"Score:      {pct}%\n"
        )


        print("Strong Areas:")

        if strong_concepts:

            for concept in strong_concepts:

                print(
                    f"✓ {concept}"
                )

        else:

            print(
                "(none yet)"
            )


        print("\nWeak Areas:")

        if weak_concepts:

            for concept in weak_concepts:

                print(
                    f"⚠ {concept}"
                )

        else:

            print(
                "(none — great work!)"
            )


        print("\nRecommended:")

        if weak_concepts:

            for concept in weak_concepts:

                print(
                    f"→ Revise {concept}"
                )

        else:

            print(
                "→ Try the next difficulty level"
            )

        print("━" * 30)


